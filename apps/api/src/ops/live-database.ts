import pg from 'pg';
import { sql } from 'drizzle-orm';
import type { Config } from '../config';
import type { Db } from '../db/client';
import { AppError } from '../lib/errors';

const DATABASE = 'gudex_live';
const ROLE = 'gudex_live_owner';
interface ExistingRole {
  rolcanlogin: boolean;
  rolsuper: boolean;
  rolcreatedb: boolean;
  rolcreaterole: boolean;
  rolreplication: boolean;
  rolbypassrls: boolean;
  has_parent_roles: boolean;
}

export async function inspectDatabase(db: Db) {
  const result = await db.execute(sql`select current_database() as database,
    current_user as role,
    (select json_build_object('superuser', rolsuper, 'createDatabase', rolcreatedb,
      'createRole', rolcreaterole, 'replication', rolreplication, 'bypassRls', rolbypassrls,
      'parentRoles', exists(select 1 from pg_auth_members where member = pg_roles.oid))
      from pg_roles where rolname = current_user) as privileges,
    (select value from app_settings where key = 'financial_mode') as mode,
    (select count(*)::int from users) as users,
    (select count(*)::int from ledger_entries) as ledger_entries,
    (select count(*)::int from deposits where provider_id = 'mock') as demo_deposits,
    (select count(*)::int from mock_upay_cards) as demo_cards,
    (select count(*)::int from card_issue_sponsorships) as issue_sponsorships,
    (select count(*)::int from card_issue_retry_consents) as additional_issue_consents,
    (select count(*)::int from deposit_invoices) as deposit_invoices,
    (select count(*)::int from deposit_invoices where state = 'credited') as credited_invoices,
    (select coalesce(json_agg(invoice_state), '[]'::json) from (
      select state, count(*)::int as count, count(order_no)::int as bound_orders,
        count(url_ciphertext)::int as checkout_receipts from deposit_invoices group by state order by state
    ) invoice_state) as deposit_invoice_states,
    (select count(*)::int from card_operation_request_aliases) as issuance_request_aliases,
    (select count(*)::int from pg_trigger where not tgisinternal and tgname in (
      'card_operation_request_aliases_guard', 'card_operations_guard_aliased_key'
    )) as issuance_alias_guard_triggers,
    (select count(*)::int from pg_trigger where not tgisinternal and tgname in (
      'card_issue_sponsorships_guard_retry', 'card_operations_guard_retry', 'ledger_transactions_guard_retry',
      'ledger_entries_guard_retry', 'card_operations_verify_retry_consent', 'card_issue_retry_consents_immutable'
    )) as additional_issue_guard_triggers,
    (select count(*)::int from pg_trigger where not tgisinternal and tgname = 'deposit_invoices_guard_identity') as invoice_guard_triggers,
    (select count(*)::int from pg_trigger where not tgisinternal and tgname in (
      'card_operations_guard_sponsored', 'ledger_transactions_guard_sponsored', 'ledger_entries_guard_sponsored'
    )) as sponsorship_guard_triggers,
    (select count(*)::int from card_operations where status in ('pending', 'processing', 'unknown')) as unresolved_cards,
    (select count(*)::int from withdrawals where status in ('pending', 'processing', 'unknown')) as unresolved_withdrawals,
    (select count(*)::int from jobs where status in ('queued', 'running')) as active_jobs`);
  return result.rows[0];
}

// One-time infrastructure setup. No existing password is returned or changed.
// The new credential is generated by the operator and belongs only to a fresh private database.
export async function prepareLiveDatabase(config: Config, rolePassword: string) {
  if (!config.LIVE_DATABASE_SETUP_ENABLED) throw new AppError('not_found', 'Not found');
  if (!/^[a-f0-9]{64}$/.test(rolePassword)) throw new AppError('validation', 'A generated 32-byte database credential is required');
  let source: URL, pooled: URL;
  try {
    source = new URL(config.DATABASE_URL_UNPOOLED ?? config.POSTGRES_URL_NON_POOLING ?? config.DATABASE_URL);
    pooled = new URL(config.DATABASE_URL);
  } catch { throw new AppError('provider_unavailable', 'Database connection configuration is invalid'); }
  if (!source.hostname.endsWith('.neon.tech') || source.hostname.split('.')[0]!.endsWith('-pooler') ||
      !pooled.hostname.endsWith('.neon.tech') ||
      pooled.hostname.replace(/^([^.]+)-pooler\./, '$1.') !== source.hostname) {
    throw new AppError('provider_unavailable', 'Live setup requires matching pooled and unpooled Neon endpoints');
  }
  if (decodeURIComponent(source.pathname.slice(1)) === DATABASE) throw new AppError('validation', 'This deployment already uses the live database');
  const admin = new pg.Client({ connectionString: source.toString(), connectionTimeoutMillis: 10000, query_timeout: 10000 });
  let connected = false;
  try {
    await admin.connect(); connected = true;
    await admin.query('select pg_advisory_lock(727279)');
    const database = await admin.query<{ owner: string }>('select pg_get_userbyid(datdba) as owner from pg_database where datname = $1', [DATABASE]);
    const role = await admin.query<ExistingRole>(`select r.rolcanlogin, r.rolsuper, r.rolcreatedb,
      r.rolcreaterole, r.rolreplication, r.rolbypassrls,
      exists(select 1 from pg_auth_members m where m.member = r.oid) as has_parent_roles
      from pg_roles r where r.rolname = $1`, [ROLE]);
    if (database.rowCount && database.rows[0]!.owner !== ROLE) throw new AppError('validation', 'The live database name is already owned by another role');
    if (role.rowCount) {
      const current = role.rows[0];
      if (!current || current.rolcanlogin !== true || current.rolsuper !== false || current.rolcreatedb !== false ||
          current.rolcreaterole !== false || current.rolreplication !== false || current.rolbypassrls !== false || current.has_parent_roles !== false) {
        throw new AppError('validation', 'The existing live role must be an unprivileged standalone login role');
      }
    }
    if (!role.rowCount) {
      // The names are fixed constants and the password is restricted to hexadecimal above.
      await admin.query(`create role "${ROLE}" login nosuperuser nocreatedb nocreaterole noreplication nobypassrls password '${rolePassword}'`);
    }
    await admin.query(`grant "${ROLE}" to current_user`);
    if (!database.rowCount) await admin.query(`create database "${DATABASE}" owner "${ROLE}" template template0`);
    const live = new URL(source);
    live.username = ROLE; live.password = rolePassword; live.pathname = `/${DATABASE}`;
    const verify = new pg.Client({ connectionString: live.toString(), connectionTimeoutMillis: 10000, query_timeout: 10000 });
    try {
      await verify.connect();
      await verify.query('select 1');
    } finally { await verify.end().catch(() => {}); }
    await admin.query(`revoke all on database "${DATABASE}" from public`);
    await admin.query(`grant connect, temporary on database "${DATABASE}" to "${ROLE}"`);
    return { database: DATABASE, role: ROLE, host: source.hostname, pooledHost: pooled.hostname,
      port: source.port || '5432', created: !database.rowCount, originalDataPreserved: true };
  } catch (error) {
    if (error instanceof AppError) throw error;
    // Do not let PostgreSQL errors containing credentials or connection strings reach logs.
    throw new AppError('provider_unavailable', 'Live database preparation failed; the original database, data and credentials were preserved');
  } finally {
    if (connected) await admin.query('select pg_advisory_unlock(727279)').catch(() => {});
    await admin.end().catch(() => {});
  }
}
